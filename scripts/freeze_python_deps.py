"""Freeze the installed Windows build/runtime dependency closure, not all site-packages."""
from __future__ import annotations

import argparse
import hashlib
import importlib.metadata as metadata
import json
import platform
from datetime import datetime, timezone
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name


ROOTS = ("PyMuPDF", "PyInstaller", "mcp", "jsonschema")


def dependency_snapshot() -> dict:
    environment = default_environment()
    pending = [(name, frozenset()) for name in ROOTS]
    processed: set[tuple[str, frozenset[str]]] = set()
    records: dict[str, dict] = {}
    while pending:
        name, extras = pending.pop()
        identifier = canonicalize_name(name)
        if (identifier, extras) in processed:
            continue
        processed.add((identifier, extras))
        distribution = metadata.distribution(name)
        record = records.setdefault(identifier, {
            "name": distribution.metadata["Name"], "version": distribution.version,
            "license": distribution.metadata.get("License-Expression") or distribution.metadata.get("License") or "See upstream license files",
            "project_urls": distribution.metadata.get_all("Project-URL") or [],
            "requires": list(distribution.requires or []), "selected_extras": [],
        })
        record["selected_extras"] = sorted(set(record["selected_extras"]) | set(extras))
        for raw in distribution.requires or []:
            requirement = Requirement(raw)
            if requirement.marker and not any(requirement.marker.evaluate({**environment, "extra": extra}) for extra in (extras or {""})):
                continue
            installed = metadata.version(requirement.name)
            if requirement.specifier and installed not in requirement.specifier:
                raise ValueError(f"Installed dependency {requirement.name} does not satisfy {distribution.metadata['Name']}'s declared requirement")
            pending.append((requirement.name, frozenset(requirement.extras)))
    return {
        "format_version": 1, "kind": "installed_dependency_closure",
        "recorded_at_utc": datetime.now(timezone.utc).isoformat(),
        "python": platform.python_version(), "platform": platform.platform(),
        "environment_markers": environment, "roots": list(ROOTS),
        "packages": [records[key] for key in sorted(records)],
        "limitations": "Versions are observed installed metadata. Wheel hashes and byte-identical rebuilds are not claimed.",
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lock", default="requirements-build.lock")
    parser.add_argument("--manifest", default="requirements-build.json")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    snapshot = dependency_snapshot()
    lines = ["# Observed complete build/runtime dependency closure for Windows x64.",
             "# Generated by scripts/freeze_python_deps.py from installed metadata.",
             "# Exact package versions; distribution hashes and identical EXEs are not claimed.",
             "--index-url https://pypi.org/simple"]
    lines.extend(f"{item['name']}=={item['version']}" for item in snapshot["packages"])
    lock = root / args.lock
    lock.write_text("\n".join(lines) + "\n", encoding="utf-8")
    snapshot["lock_sha256"] = hashlib.sha256(lock.read_bytes()).hexdigest()
    (root / args.manifest).write_text(json.dumps(snapshot, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"status": "frozen", "packages": len(snapshot["packages"]), "lock_sha256": snapshot["lock_sha256"]}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
