def freeze(seal: Path | None = None, target: Path | None = None, review_manifest: Path | None = None, transcription: Path | None = None):
    import pymupdf
    seal = seal or ROOT / "bench" / "holdout_seal_manifest.json"
    target = target or ROOT / "bench" / "D.jsonl"
    manual = json.loads(transcription.read_text(encoding="utf-8")) if transcription else MANUALLY_TRANSCRIBED
    if target.exists():
        raise ValueError("D真值已封存，禁止覆盖已见过的保留集")
    sealed = json.loads(seal.read_text(encoding="utf-8"))
    records = []
    for report in sealed["reports"]:
        path = Path(report["path"])
        if sha256_file(path) != report["sha256"]:
            raise ValueError("原PDF与预先封存哈希不匹配")
        document = pymupdf.open(path)
        for account, label, page_number, current, previous in manual[report["ticker"]]:
            page = document[page_number - 1]
            for year, original in ((2023, current), (2022, previous)):
                boxes = page.search_for(original)
                if not boxes:
                    raise ValueError(f"人工审查数值无法定位：{report['company']} {original}")
                # A value may appear again in a later fast-report comparison on
                # the same page. The manually reviewed primary table is first.
                box = sorted(boxes, key=lambda item: (item.y0, item.x0))[0]
                text = page.get_textbox(box).strip()
                if Decimal(text.replace(",", "")) != Decimal(original.replace(",", "")):
                    raise ValueError("数值单元格读取与人工转录不一致")
                record = {
                    "id": f"{target.stem}-{report['ticker']}-{account}-{year}", "ticker": report["ticker"],
                    "company": report["company"], "account": account, "label": label, "period": f"{year}Y",
                    "scope": "合并", "nr": "未扣非", "unit": "元", "unit_scale": "1",
                    "value": original.replace(",", ""), "document_sha256": report["sha256"],
                    "source_path": report["path"], "publish_date": report["publish_date"],
                    "page": page_number, "bbox": list(box), "search_text": original, "cell_text": text,
                    "evidence_id": make_evidence_id(report["sha256"], page_number, text, tuple(box)),
                    "table_label": "主要会计数据/盈利能力" if account != "CFO" else "主要会计数据/营运情况",
                    "column_label": f"{year}年" if report["ticker"] not in {"920003", "920009"} else "本期" if year == 2023 else "上年同期",
                    "gold_source": "manual_original_pdf", "reviewer": "Codex original-PDF review",
                    "review_method": "Read original PDF table headers, units, labels and current/comparative cells; no production parser used",
                    "reviewed_at": datetime.now(timezone.utc).isoformat(), "independent_second_review": False,
                }
                records.append(record)
        document.close()
    target.write_text("".join(json.dumps(row, ensure_ascii=False) + "\n" for row in records), encoding="utf-8")
    review = {"gold_sha256": sha256_file(target), "gold_cells": len(records), "company_count": len(sealed["reports"]), "finished_at": datetime.now(timezone.utc).isoformat(), "code_seal_sha256": sha256_file(seal), "producer_sha256": sha256_file(Path(__file__)), "independent_second_review": False}
    (review_manifest or ROOT / "bench" / "holdout_gold_review_manifest.json").write_text(json.dumps(review, ensure_ascii=False, indent=2), encoding="utf-8")
    return review


