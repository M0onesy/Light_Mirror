def table(header: list[str], rows: list[list[str]]) -> str:
    out = ["<table><tr>" + "".join(f"<th>{h}</th>" for h in header) + "</tr>"]
    for r in rows:
        out.append("<tr>" + "".join(f"<td{' class=n' if i else ''}>{c}</td>" for i, c in enumerate(r)) + "</tr>")
    return "".join(out) + "</table>"


