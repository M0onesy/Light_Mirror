@dataclass(frozen=True)
class SemanticBinding:
    """A model submits identifiers and enums, never a financial value."""
    mention_id: str
    company: str
    account: str
    period: str
    scope: str = "合并"
    nr: str = "未扣非"
    relation: str = "value"
    base_period: str | None = None
    modality: str = "fact"
    declared_source: str | None = None
    note: str = ""

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    def agreement_key(self) -> tuple:
        return (self.company, self.account, self.period, self.scope, self.nr,
                self.relation, self.base_period, self.modality, self.declared_source)

    @classmethod
    def from_dict(cls, value: dict[str, Any]) -> "SemanticBinding":
        from dataclasses import fields
        import re
        if set(value) - {item.name for item in fields(cls)}:
            raise ValueError("绑定包含未授权字段；不得提交数值、公式或判定")
        if re.search(r"[0-9０-９]", str(value.get("note", ""))):
            raise ValueError("绑定说明不得包含自由数字")
        if value.get("scope", "合并") not in {"合并", "母公司", "未知"}:
            raise ValueError("未知口径枚举")
        if value.get("nr", "未扣非") not in {"未扣非", "扣非", "未知"}:
            raise ValueError("未知扣非枚举")
        if value.get("modality", "fact") not in {"fact", "inference", "opinion", "forecast"}:
            raise ValueError("未知陈述性质枚举")
        if value.get("relation", "value") not in {"value", "yoy", "qoq", "gt", "lt", "ge", "le", "eq", "pp_difference", "ratio", "share", "cagr", "unknown"}:
            raise ValueError("未知关系枚举")
        return cls(**value)

