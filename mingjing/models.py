from __future__ import annotations

from dataclasses import asdict, dataclass, field
from decimal import Decimal
from typing import Any


@dataclass(frozen=True)
class Evidence:
    evidence_id: str
    document: str
    page: int | None = None
    bbox: tuple[float, float, float, float] | None = None
    text: str = ""
    row: int | None = None
    col: int | None = None
    document_sha256: str = ""

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass(frozen=True)
class Fact:
    fact_id: str
    company: str
    account: str
    period: str
    scope: str = "合并"
    nr: str = "未扣非"
    version: str = "原披露"
    source_doc: str = ""
    publish_date: str = ""
    value: Decimal = Decimal("0")
    decimals: int = 2
    display_unit: str = "元"
    evidence: tuple[str, ...] = ()
    label: str = ""
    source_path: str = ""
    source_type: str = "structured"
    table_label: str = ""
    column_label: str = ""
    parse_conf: str = "1"
    extractor_version: str = "legacy-structured"
    version_group: str = ""
    dimension_kind: str = "total"
    dimension_id: str = ""
    currency: str = "CNY"
    definition_id: str = ""
    # A disclosed table is an independent source identity, not evidence that
    # an otherwise unlabelled amount uses consolidated accounting scope.
    source_table_id: str = ""
    source_table_evidence: tuple[str, ...] = ()
    source_scope_evidence: tuple[str, ...] = ()
    source_row_index: int = 0
    # A disclosed growth column is not an amount operand. Only source-table
    # transcription queries may explicitly request a non-value relation.
    source_relation: str = "value"

    def __post_init__(self) -> None:
        if self.source_relation not in {'value', 'yoy'}:
            raise ValueError('来源单元格关系须为 value 或 yoy')
        if self.source_relation == 'yoy' and self.display_unit not in {'%', '％'}:
            raise ValueError('来源同比列必须具有明确百分比单位，不能作为金额')
        if type(self.source_row_index) is not int or not 0 <= self.source_row_index <= 10000:
            raise ValueError('来源表行序号须为非负整数；零表示未登记')
        if not isinstance(self.value, Decimal) or not self.value.is_finite():
            raise ValueError("Fact.value 必须为有限 Decimal 数值")
        confidence = Decimal(str(self.parse_conf))
        if not confidence.is_finite() or not Decimal("0") <= confidence <= Decimal("1"):
            raise ValueError("Fact.parse_conf 必须在零与一之间")
        from .dimensions import validate_fact_dimensions
        validate_fact_dimensions(self.dimension_kind, self.dimension_id, self.currency, self.definition_id)

    def to_dict(self) -> dict[str, Any]:
        data = asdict(self)
        data["value"] = str(self.value)
        data["evidence"] = list(self.evidence)
        data['source_table_evidence'] = list(self.source_table_evidence)
        data['source_scope_evidence'] = list(self.source_scope_evidence)
        return data


@dataclass(frozen=True)
class FactQueryOutcome:
    """A failed lookup explains why; absence is not equivalent to conflict."""
    status: str
    fact: Fact | None = None
    reason: str | None = None
    evidence: tuple[str, ...] = ()
    candidate_fact_ids: tuple[str, ...] = ()

    @property
    def abstention_code(self) -> str | None:
        if self.status == "found":
            return None
        return "X4" if self.status in {
            "conflict", "low_confidence", "unknown_date", "ambiguous_source", "invalid_interval"
        } else "X1"

    def to_dict(self) -> dict[str, Any]:
        return {"status": self.status, "fact": self.fact.to_dict() if self.fact else None,
                "reason": self.reason, "evidence": list(self.evidence),
                "candidate_fact_ids": list(self.candidate_fact_ids)}


@dataclass(frozen=True)
class AtomicClaim:
    claim_id: str
    text: str
    start: int
    end: int
    claim_type: str = "numeric"
    company: str = ""
    account: str = ""
    period: str = ""
    candidate_value: str | None = None
    unit: str = ""
    caliber_hint: tuple[str, ...] = ()
    declared_source: str | None = None
    relation: str = "value"
    base_period: str | None = None
    display_decimals: int | None = None
    numeric_text: str = ""
    binding_status: str = "single"
    parse_status: str = "parsed"
    modality: str = "fact"
    query_strategy: str = "latest_as_of"
    approximate: bool = False
    table_context: dict[str, Any] = field(default_factory=dict)
    # Offset of this numeric occurrence within untouched ``text``. It is
    # generated by deterministic extraction, never by a semantic binding.
    # Absolute document offsets alone cannot disambiguate repeated values
    # when a sentence is evaluated or replayed in isolation.
    source_numeric_start: int | None = None

    def to_dict(self) -> dict[str, Any]:
        data = asdict(self)
        data["caliber_hint"] = list(self.caliber_hint)
        return data


